// BS year 2000 starts on AD 1943-04-14
const BS_START_YEAR = 2000
const AD_START = new Date(1943, 3, 14) // month is 0-indexed

/**
 * Convert AD date string (YYYY-MM-DD) to BS date string (YYYY-MM-DD).
 * Returns empty string if out of supported range.
 */
export function adToBs(adDateStr) {
  if (!adDateStr) return ''

  const adDate = new Date(adDateStr + 'T00:00:00')
  if (isNaN(adDate)) return ''

  // Days elapsed since BS 2000-01-01 (AD 1943-04-14)
  const diffMs   = adDate - AD_START
  if (diffMs < 0) return '' // before supported range
  let   daysLeft = Math.floor(diffMs / 86400000)

  let bsYear  = BS_START_YEAR
  let bsMonth = 1
  let bsDay   = 1

  // Walk through BS years
  for (let y = 0; y < BS_DATA.length; y++) {
    const yearDays = BS_DATA[y][0]
    if (daysLeft < yearDays) break
    daysLeft -= yearDays
    bsYear++
  }

  const idx = bsYear - BS_START_YEAR
  if (idx < 0 || idx >= BS_DATA.length) return ''

  // Walk through months of the BS year
  for (let m = 1; m <= 12; m++) {
    const monthDays = BS_DATA[idx][m]
    if (daysLeft < monthDays) {
      bsMonth = m
      bsDay   = daysLeft + 1
      break
    }
    daysLeft -= monthDays
  }

  return `${bsYear}-${String(bsMonth).padStart(2,'0')}-${String(bsDay).padStart(2,'0')}`
}

